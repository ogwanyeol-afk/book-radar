def topic_of(word: str) -> str | None:
    """단어가 속한 주제(가장 먼저 매칭되는 것)."""
    w = word.lower()
    for name, spec in TOPICS.items():
        for k in spec["keywords"]:
            if _match(w, k):
                return name
    return None


def _match(word: str, kw: str) -> bool:
    if word == kw:
        return True
    if kw.isascii():
        # 'ai'가 'daily'에 걸리지 않도록 짧은 영문은 접두 일치만
        return len(kw) >= 4 and kw in word
    if len(kw) == 1:
        return False  # '꽃'은 정확히 일치할 때만
    return kw in word
